def escape(text: str) -> str:
    return (text.replace("\\", "\\\\").replace("\n", "\\n")
                .replace("\r", "\\r").replace("\t", "\\t"))


def tokenize(url: str, text: str) -> list[int]:
    body = json.dumps({"content": text}).encode()
    request = urllib.request.Request(url, data=body,
                                     headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.load(response)["tokens"]


def main() -> int:
    url = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8091/tokenize"
    path = pathlib.Path(__file__).resolve().parents[1] / "tests/fixtures/tokenizer.txt"
    rows = [(text, tokenize(url, text)) for text in CORPUS]
    with path.open("w") as handle:
        handle.write("# Token ids produced by llama.cpp's /tokenize on the very GGUF this\n")
        handle.write("# engine reads. Generated by tools/make_tokenizer_fixture.py.\n")
        handle.write("# Format: <escaped input>\\t<id,id,...>   escape: \\\\ \\n \\r \\t\n")
        for text, ids in rows:
            handle.write(escape(text) + "\t" + ",".join(map(str, ids)) + "\n")
    print(f"wrote {path} with {len(rows)} cases")
    return 0


