#!/usr/bin/env python3
"""Write tests/fixtures/parity.txt: llama.cpp's pooled vectors for a few inputs.

The gate for the forward pass is cosine against this file, not against this
project's own CPU implementation: llama.cpp is an independent implementation of
the same checkpoint, so agreeing with it is evidence about the model, while
agreeing with our own reference only proves the GPU path matches the CPU path.

    scripts/hip-shell.sh 'python3 tools/make_parity_fixture.py http://127.0.0.1:8091'
"""
import json
import pathlib
import sys
import urllib.request

# Short enough that the CPU reference forward stays in the tens of seconds, long
# enough that the template and the pooling position are both exercised.
CASES = [
    "hello world",
    "The quick brown fox jumps over the lazy dog.",
    "Instruct: Given a web search query, retrieve relevant passages that answer the query\nQuery: what is a Strix Halo",
    "Il gatto dorme sul divano.",
    "def fibonacci(n):\n    return n if n < 2 else fibonacci(n - 1) + fibonacci(n - 2)",
    "東京は日本の首都です、人口は約1400万人です。",
]


def embed(url: str, text: str) -> list[float]:
    body = json.dumps({"content": text}).encode()
    request = urllib.request.Request(url, data=body,
                                     headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=600) as response:
        vector = json.load(response)[0]["embedding"]
    return vector[0] if isinstance(vector[0], list) else vector


def main() -> int:
    url = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8091/embedding"
    path = pathlib.Path(__file__).resolve().parents[1] / "tests/fixtures/parity.txt"
    with path.open("w") as handle:
        handle.write("# Pooled, L2-normalised vectors from llama.cpp for this GGUF.\n")
        handle.write("# Generated by tools/make_parity_fixture.py. Format: <input>\\t<v,v,...>\n")
        for text in CASES:
            vector = embed(url, text)
            joined = ",".join(f"{value:.9g}" for value in vector)
            handle.write(text.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")
                         + "\t" + joined + "\n")
            print(f"{len(vector):5d} dims  {text[:56]!r}")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())